export const CLIENTS_STORAGE_KEY = 'unity_client_partners'

export function getStoredClients() {
    try {
        const saved = localStorage.getItem(CLIENTS_STORAGE_KEY)
        if (saved) {
            const parsed = JSON.parse(saved)
            if (Array.isArray(parsed) && parsed.length > 0) {
                return parsed
            }
        }
    } catch (e) {
        console.error('Failed to load clients', e)
    }
    return initialClients
}

export function saveStoredClients(updatedList) {
    try {
        localStorage.setItem(CLIENTS_STORAGE_KEY, JSON.stringify(updatedList))
    } catch (e) {
        console.error('Failed to save clients', e)
    }
}

export function resetToDefaultClients() {
    try {
        localStorage.setItem(CLIENTS_STORAGE_KEY, JSON.stringify(initialClients))
    } catch (e) {
        console.error('Failed to reset clients', e)
    }
    return initialClients
}
